// A draft is a Markdown sheet in drafts\ written by the chat model from one suggestion.
// The model returns JSON in DraftReplySchema; nudge renders the Markdown itself, scans it
// for secrets and records it with status draft and source llm until nudge approve.

export const DraftReplySchema = z.strictObject({
  intro: z.string().max(600),
  sections: z
    .array(
      z.strictObject({
        heading: z.string().min(1).max(80),
        body: z.string().min(1).max(2500),
      }),
    )
    .min(1)
    .max(8),
});
export type DraftReply = z.infer<typeof DraftReplySchema>;

const DRAFT_JSON_SCHEMA = z.toJSONSchema(DraftReplySchema);

const SYSTEM_PROMPT = [
  'You write short, practical cheat sheets for a developer.',
  'Reply with one JSON object and nothing else: {"intro": one or two sentences, "sections": [{"heading": "...", "body": "..."}]}.',
  'Each body is Markdown: short bullet points and fenced code blocks with real commands or snippets. 2 to 6 sections.',
  'Only include commands you are sure exist. No headings inside a body. Plain punctuation, no em dashes.',
].join('\n');

const FENCE = /^ {0,3}(`{3,}|~{3,})/;

/**
 * Plain punctuation whatever the model wrote: em dashes become commas, en dashes hyphens.
 * Heading lines outside code fences lose their "#" so a body cannot add sections of its own;
 * "#" comments inside fences are kept.
 */
function cleanBody(body: string): string {
  let fence: string | null = null;
  return body
    .replace(/\r\n?/g, '\n')
    .replace(/[\u0000-\u0008\u000b-\u001f\u007f]/g, '')
    .replace(/\s*—\s*/g, ', ')
    .replace(/–/g, '-')
    .split('\n')
    .map((line) => {
      const f = FENCE.exec(line);
      if (f) {
        if (fence === null) fence = f[1]!;
        else if (f[1]![0] === fence[0] && f[1]!.length >= fence.length) fence = null;
        return line;
      }
      return fence === null ? line.replace(/^ {0,3}#{1,6}\s+/, '') : line;
    })
    .join('\n')
    .trim();
}

export function renderDraft(title: string, reply: DraftReply, provenance: { model: string; at: string; via?: string }): string {
  const parts = [`# ${title}`, `_Generated by ${provenance.model} on ${provenance.at} ${provenance.via ?? 'with nudge suggest'}._`];
  const intro = plainLine(reply.intro);
  if (intro) parts.push(intro);
  for (const s of reply.sections) {
    const body = cleanBody(s.body);
    if (body) parts.push(`## ${plainLine(s.heading)}\n\n${body}`);
  }
  return parts.join('\n\n') + '\n';
}

export function parseJson(raw: string): unknown {
  const text = raw.trim().replace(/^```(?:json)?\s*\n?([\s\S]*?)\n?```$/i, '$1').trim();
  try {
    return JSON.parse(text);
  } catch {
    return undefined;
  }
}

/** Ask the chat model for the sheet body. One retry at temperature 0, then a NudgeError. */
export async function writeDraftBody(client: OllamaClient, model: string, suggestion: Suggestion, projectTags: string[]): Promise<DraftReply> {
  const user = [
    `Title: ${suggestion.title}`,
    `Tags: ${suggestion.tags.join(', ')}`,
    `The project uses: ${projectTags.join(', ')}`,
    `Cover: ${suggestion.outline.join('; ')}`,
  ].join('\n');
  let lastProblem = '';
  for (const temperature of [0.3, 0]) {
    let raw: string;
    try {
      raw = await client.chat({
        model,
        temperature,
        schema: DRAFT_JSON_SCHEMA,
        timeoutMs: 300_000,
        messages: [
          { role: 'system', content: SYSTEM_PROMPT },
          { role: 'user', content: user },
        ],
      });
    } catch (e) {
      if (isOllamaDown(e) || (e instanceof OllamaError && e.kind === 'model-missing')) throw new NudgeError(`writing the draft needs the chat model: ${errorMessage(e)}`);
      lastProblem = errorMessage(e);
      continue;
    }
    const parsed = DraftReplySchema.safeParse(parseJson(raw));
    if (parsed.success) return parsed.data;
    lastProblem = 'the reply was not JSON in the expected shape';
  }
  throw new NudgeError(`the model gave no usable draft twice (${lastProblem}); nothing was saved.`);
}

export interface DraftResult {
  sheet: Sheet;
  sections: number;
  /** Sections embedded right away (the rest wait for nudge index). */
  embedded: number;
  warnings: string[];
}

/**
 * Write a suggestion as a draft sheet: model call, render, secret scan, then under the
 * lock write drafts\<id>-<slug>.md, record it in manifest.json, index it and commit both.
 */
export async function saveDraft(config: Config, suggestion: Suggestion, ctx: { project: string; projectTags: string[] }, client: OllamaClient = ollamaClient(config.ollama)): Promise<DraftResult> {
  const health = await client.health();
  if (!health.ok) throw new NudgeError(`writing the draft needs the chat model, and ${health.reason}. Start Ollama and try again.`);
  const model = config.ollama.chatModel;
  const at = today();
  const reply = await writeDraftBody(client, model, suggestion, ctx.projectTags);
  const text = renderDraft(suggestion.title, reply, { model, at });
  const findings = blockingFindings(scanSecrets(text, []));
  if (findings.length) {
    throw new NudgeError(`the draft looks like it contains a secret (${findings.map((f) => `line ${f.line} ${f.rule}`).join(', ')}); nothing was saved.`);
  }
  return withLock('suggest', async () => {
    const r = recordDraft(config.library, { title: suggestion.title, tags: suggestion.tags, text, llm: { model, at, project: ctx.project } });
    const warnings = [...r.warnings];
    let embedded = 0;
    if (config.ollama.embedModel) {
      try {
        const db = openDb();
        try {
          const e = await embedIndex(db, client, config.ollama.embedModel);
          embedded = e.embedded;
          if (e.skipped) warnings.push(`not embedded yet (${e.skipped}); nudge index does it later`);
        } finally {
          db.close();
        }
      } catch (e) {
        warnings.push(`saved, but embedding failed: ${errorMessage(e)}`);
      }
    }
    refreshHookCache(config);
    return { sheet: r.sheet, sections: r.sections, embedded, warnings };
  });
}

export interface DraftInput {
  title: string;
  tags: string[];
  /** Rendered Markdown, already secret-scanned by the caller. */
  text: string;
  llm: LlmInfo;
  /** Set for drafts nudge harvest wrote from a chat. */
  harvest?: HarvestInfo;
}

/**
 * Write a draft into drafts\<id>-<slug>.md, record it in manifest.json, keyword-index it and
 * commit both. Embeddings are left to the caller. Call with the nudge.lock held.
 */
export function recordDraft(library: string, input: DraftInput): { sheet: Sheet; sections: number; warnings: string[] } {
  ensureLibrary(library);
  const sheets = readManifest(library);
  const id = nextId(sheets);
  const rel = `drafts/${id}-${slugify(input.title)}.md`;
  const file = path.join(library, ...rel.split('/'));
  const sha = sha256(input.text);
  const sheet: Sheet = {
    id,
    title: input.title,
    file: rel,
    originalPath: input.harvest?.origin ?? '',
    sha256: sha,
    format: 'md',
    tags: input.tags,
    status: 'draft',
    source: 'llm',
    learned: false,
    lastVerified: input.llm.at,
    updatedAt: input.llm.at,
    secretAllowlist: [],
    llm: input.llm,
    ...(input.harvest ? { harvest: input.harvest } : {}),
  };
  writeFileAtomic(file, input.text);
  try {
    writeManifest(library, [...sheets, sheet]);
  } catch (e) {
    fs.rmSync(file, { force: true });
    throw new NudgeError(`could not write manifest.json (${errorMessage(e)}); the draft was not saved.`);
  }
  writeExtractCache(sha, input.text);

  const warnings: string[] = [];
  const sections = chunkMarkdown(input.text);
  try {
    const db = openDb();
    try {
      indexSheet(db, sheet, sections);
    } finally {
      db.close();
    }
  } catch (e) {
    warnings.push(`saved, but indexing failed: ${errorMessage(e)}`);
  }
  const commit = commitPaths(library, ['manifest.json', rel], `nudge: draft ${id} ${input.title}`);
  if (!commit.ok) warnings.push(`saved, but the Git commit failed: ${commit.stderr || 'unknown error'}`);
  return { sheet, sections: sections.length, warnings };
}
